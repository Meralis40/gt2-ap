// The text compressed in kDeflateDynamic.
std::string words()
{
    std::string s;
    for (int i = 0; i < 3000; ++i)
        s += "word" + std::to_string(i * i % 97) + " ";
    return s;
}

std::string str(const std::vector<std::uint8_t>& v) { return {v.begin(), v.end()}; }

void putLe32(std::vector<std::uint8_t>& v, std::size_t pos, std::uint32_t x)
{
    for (int i = 0; i < 4; ++i)
        v[pos + static_cast<std::size_t>(i)] = static_cast<std::uint8_t>(x >> (8 * i));
}

// Two-entry GT2.OVL built like the real one (entries 4-byte aligned).
std::vector<std::uint8_t> syntheticOvl()
{
    std::vector<std::uint8_t> ovl(16);
    putLe32(ovl, 0, 16);
    putLe32(ovl, 4, sizeof kGzOverlayA);
    ovl.insert(ovl.end(), std::begin(kGzOverlayA), std::end(kGzOverlayA));
    ovl.resize((ovl.size() + 3) & ~std::size_t{3});
    putLe32(ovl, 8, static_cast<std::uint32_t>(ovl.size()));
    putLe32(ovl, 12, sizeof kGzOverlayB);
    ovl.insert(ovl.end(), std::begin(kGzOverlayB), std::end(kGzOverlayB));
    return ovl;
}

