"""Lists, for each unit, the PlayStation address of every function the port defines.

Guest data holds function addresses (menu pages, state tables, callbacks) as the
console had them, in game_function words (rt/gptr.h), and a call through one looks the
address up in these tables: functions_<unit>.cpp holds addresses and names only. The
overlays share their addresses, so rt::callTarget searches the loaded overlay's table,
then the executable's (rt/functions.cpp).

    gen_functions.py --defined <names> --out-dir port/gen

--defined takes the names the port defines, one a line, as `nm --defined-only` writes
them (port/tools/update_syms.sh). Run from WSL with any python3.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SYMBOLS = ROOT / "decomp" / "sim" / "symbols"
UNITS = ["exe", "ovl0", "ovl1", "ovl2", "ovl3", "ovl4", "ovl5"]


def read_functions(unit):
    functions = {}
    for line in (SYMBOLS / f"{unit}.txt").read_text(encoding="utf-8").splitlines():
        parts = line.split(";")[0].split("=")
        if len(parts) == 2 and "type:func" in line:
            functions.setdefault(int(parts[1].strip(), 16), parts[0].strip())
    return functions


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--defined", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, required=True)
    args = parser.parse_args()

    defined = set()
    for line in args.defined.read_text(encoding="utf-8").splitlines():
        name = line.strip()
        defined.add(name[1:] if name.startswith("_") else name)

    for unit in UNITS:
        entries = sorted((a, n) for a, n in read_functions(unit).items() if n in defined)
        names = sorted({n for _, n in entries})
        with (args.out_dir / f"functions_{unit}.cpp").open("w", encoding="utf-8", newline="\n") as out:
            out.write("// Generated by port/tools/gen_functions.py.\n#include \"rt/functions.h\"\n\n"
                      "extern \"C\" {\n")
            out.writelines(f"void {n}();\n" for n in names)
            out.write("}\n\n")
            out.write(f"extern const rt::FunctionEntry g_Functions_{unit}[] = {{\n")
            out.writelines(f"    {{0x{a:08x}u, {n}}},\n" for a, n in entries)
            out.write("    {0, nullptr},\n};\n")
        print(f"{unit}: {len(entries)} functions")


if __name__ == "__main__":
    main()
