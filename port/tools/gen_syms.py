"""Binds the game's external names to their guest addresses.

Reads the names a build leaves undefined, one a line (from `nm -u`, with the
COFF `_` prefix or without), and the symbol files in decomp/sim/symbols, and
writes guest_syms.S. Names of data go there; names of functions are code the
port has to provide, so they go to the report instead, and so do names no
symbol file knows.

The two names with different addresses per unit are in the report's conflicts:
the units that use them need their own names (`-D`).
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SYMBOLS = ROOT / "decomp" / "sim" / "symbols"
LINE = re.compile(r"^\s*(\S+)\s*=\s*(0x[0-9A-Fa-f]+)\s*;(.*)$")
ADDRESS_NAME = re.compile(r"^_?(D_([0-9A-F]{8}))$")  # splat's name for a label with no symbol
UNITS = ["exe", "ovl0", "ovl1", "ovl2", "ovl3", "ovl4", "ovl5"]


def read_symbols():
    table = {}
    for unit in UNITS:
        for line in (SYMBOLS / f"{unit}.txt").read_text(encoding="utf-8").splitlines():
            if m := LINE.match(line):
                name, addr, rest = m.groups()
                table.setdefault(name, []).append((unit, int(addr, 16), "type:func" in rest))
    return table


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("undefined", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    args = parser.parse_args()

    table = read_symbols()
    names = sorted({l.strip() for l in args.undefined.read_text(encoding="utf-8").splitlines() if l.strip()})
    data, functions, conflicts, unknown = [], [], [], []
    for raw in names:
        name = raw[1:] if raw.startswith("_") and raw[1:] in table else raw
        entries = table.get(name)
        if not entries and (m := ADDRESS_NAME.match(raw)):
            data.append((m.group(1), int(m.group(2), 16)))
        elif not entries:
            unknown.append(raw)
        elif any(e[2] for e in entries):
            functions.append(name)
        elif len({e[1] for e in entries}) > 1:
            conflicts.append(f"{name} " + " ".join(f"{u}:{a:08x}" for u, a, _ in entries))
        else:
            data.append((name, entries[0][1]))

    with args.out.open("w", encoding="utf-8", newline="\n") as out:
        out.write("/* Generated by port/tools/gen_syms.py. */\n")
        out.write("#if defined(_WIN32)\n#define SYM(n) _##n\n#else\n#define SYM(n) n\n#endif\n")
        for name, addr in data:
            out.write(f"    .globl SYM({name})\n    .set   SYM({name}), 0x{addr:08x}\n")
        out.write('#if defined(__linux__)\n    .section .note.GNU-stack,"",@progbits\n#endif\n')

    with args.report.open("w", encoding="utf-8", newline="\n") as out:
        for title, items in (("functions", functions), ("conflicts", conflicts), ("unknown", unknown)):
            out.write(f"# {title}: {len(items)}\n")
            out.writelines(f"{i}\n" for i in items)
    print(f"{len(data)} data, {len(functions)} functions, {len(conflicts)} conflicts, {len(unknown)} unknown")


if __name__ == "__main__":
    sys.exit(main())
