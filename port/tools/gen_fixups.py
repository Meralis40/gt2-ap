"""Finds the guest code addresses in the game's data.

Guest data holds function addresses (menu pages, state tables, callbacks), but
the functions run as host code. This scans the data segments of the original
files and writes, for each unit, the slots to patch after the unit is loaded:
fixups_<unit>.cpp holds addresses and function names only, no game data.

Run it with decomp/.venv's Python (it needs yaml), from WSL. --defined takes the
names the port defines, one a line, as `nm --defined-only` writes them. Slots
whose function the port doesn't define by that name go to the report.
"""
import argparse
import struct
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
DECOMP = ROOT / "decomp"
SYMBOLS = DECOMP / "sim" / "symbols"
UNITS = ["exe", "ovl0", "ovl1", "ovl2", "ovl3", "ovl4", "ovl5"]
DATA_TYPES = {"data", ".data", "rodata", ".rodata", "rdata"}
# Data that happens to equal a function's address: a font's glyph for '+', and two flag words.
NOT_POINTERS = {0x800983b4, 0x800992a0, 0x8009a4b0}


def read_functions(unit):
    functions, labels = {}, []
    for line in (SYMBOLS / f"{unit}.txt").read_text(encoding="utf-8").splitlines():
        parts = line.split(";")[0].split("=")
        if len(parts) != 2:
            continue
        name, addr = parts[0].strip(), int(parts[1].strip(), 16)
        labels.append((addr, name))
        if "type:func" in line:
            functions.setdefault(addr, name)
    return functions, sorted(labels)


def data_ranges(config):
    """Yields (file start, file end, vram of start) for each data subsegment."""
    segments = config["segments"]
    for index, segment in enumerate(segments):
        if not isinstance(segment, dict) or "subsegments" not in segment:
            continue
        following = next(s for s in segments[index + 1:])
        segment_end = following[0] if isinstance(following, list) else following["start"]
        subsegments = segment["subsegments"]
        base_rom, base_vram = segment["start"], segment["vram"]
        for i, sub in enumerate(subsegments):
            if not isinstance(sub, list) or sub[1] not in DATA_TYPES:
                continue
            end = next((s[0] for s in subsegments[i + 1:] if isinstance(s, list)), segment_end)
            yield sub[0], end, base_vram + sub[0] - base_rom


def owner(labels, addr):
    low, high = 0, len(labels)
    while low < high:
        mid = (low + high) // 2
        if labels[mid][0] <= addr:
            low = mid + 1
        else:
            high = mid
    return labels[low - 1][1] if low else ""


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--defined", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    args = parser.parse_args()

    defined = set()
    for line in args.defined.read_text(encoding="utf-8").splitlines():
        name = line.strip()
        defined.add(name[1:] if name.startswith("_") else name)

    resident, _ = read_functions("exe")
    report = []
    total = 0
    for unit in UNITS:
        config = yaml.safe_load((DECOMP / "sim" / f"{unit}.yaml").read_text(encoding="utf-8"))
        image = (DECOMP / "baserom" / "sim" / ("SCUS_944.88" if unit == "exe" else f"{unit}.bin")).read_bytes()
        functions, labels = read_functions(unit)
        table = {} if unit == "exe" else resident
        slots = []
        for start, end, vram in data_ranges(config):
            for offset in range(start & ~3, end - 3, 4):
                word = struct.unpack_from("<I", image, offset)[0]
                name = functions.get(word) or table.get(word)
                if name is None:
                    continue
                slot = vram + offset - start
                holder = owner(labels, slot)
                if "vtable" in holder or "__vt" in holder or slot in NOT_POINTERS:
                    continue
                if name in defined:
                    slots.append((slot, name))
                else:
                    report.append(f"{unit} {slot:08x} {holder} -> {name}")
        names = sorted({n for _, n in slots})
        with (args.out_dir / f"fixups_{unit}.cpp").open("w", encoding="utf-8", newline="\n") as out:
            out.write("// Generated by port/tools/gen_fixups.py.\n#include \"rt/fixups.h\"\n\nextern \"C\" {\n")
            out.writelines(f"void {n}();\n" for n in names)
            out.write("}\n\n")
            out.write(f"extern const rt::Fixup g_Fixups_{unit}[] = {{\n")
            out.writelines(f"    {{0x{s:08x}u, {n}}},\n" for s, n in slots)
            out.write(f"    {{0, nullptr}},\n}};\n")
        print(f"{unit}: {len(slots)} slots")
        total += len(slots)
    args.report.write_text("\n".join(report) + "\n", encoding="utf-8", newline="\n")
    print(f"{total} slots, {len(report)} unmatched")


if __name__ == "__main__":
    main()
