# Dumps the opponent cars of every GT mode event, with the power and weight the game computes for
# them, to JSON and Markdown. The AP world logic uses it for the power target of the events.
#
# Inputs, all from the Simulation disc (USA):
#   gt2-discinfo extract <disc.cue> /SCUS_944.88 <dir>/SCUS_944.88
#   gt2-discinfo overlays <disc.cue> <dir>                      (only ovl4.bin is used)
#   gt2-discinfo vol extract <disc.cue> <dir> /carparam
# then (needs `pip install unicorn`):
#   python scripts/data/dump_opponents.py <dir> "docs/game ids/opponents.json" "docs/game ids/opponents.md"
#
# An event of the race data (table 0) starts with up to 16 opponent IDs at +0x04 (an IdList,
# RaceSetup_InitEvent). The low 16 bits of an ID are a 1-based entry of race data table 1: a car
# entry with its own tuned setup, whose first word is the car ID (RaceCarPick_Random). The bits
# 26-31 are a colour. RaceSetup_InitEvent draws the AI cars at random from the list.
#
# Power and weight come from the game's own code, run like GTBattleMenu does for the free races
# (BattleTable_LoadNext): CarSetup_InitFromCarEntry, CarParams_BuildFromSetup, then
# CarParams_GetPerformance. That power is the one Race_CheckEntry compares with a power limit.

import gzip
import json
import statistics
import struct
import sys
from pathlib import Path

from dump_cars import DATA, SCRATCH, Game
from dump_events import decode_car, gtdt_tables

GAMEDATA_RELOCATE = 0x80076ae8
CARSETUP_INIT_FROM_CAR_ENTRY = 0x80076f5c
CARPARAMS_BUILD_FROM_SETUP = 0x800771ac
CARPARAMS_GET_PERFORMANCE = 0x80075930
G_GTMODE_RACE_DATA = 0x80092870
G_GTMODE_RACE_ENTRY_SIZES = 0x80092490
RACE = 0x80400000

EVENT_SIZE, CAR_ENTRY_SIZE = 0x9c, 0x60
OPPONENT_IDS = 0x04
CARPARAMS_WEIGHT, CARPARAMS_DRIVETRAIN = 0x5a, 0x8a
DRIVETRAINS = ["FR", "FF", "AWD", "MR", "RR"]


def main():
    vol, json_out, md_out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    data = gzip.decompress((vol / "carparam/usa_gtmode_data.dat.gz").read_bytes())
    race = gzip.decompress((vol / "carparam/usa_gtmode_race.dat.gz").read_bytes())
    game = Game((vol / "SCUS_944.88").read_bytes(), (vol / "ovl4.bin").read_bytes(), data)
    assert RACE > DATA + len(data) and RACE + len(race) < SCRATCH
    game.write(RACE, race)
    game.call(GAMEDATA_RELOCATE, RACE, G_GTMODE_RACE_ENTRY_SIZES)
    game.write32(G_GTMODE_RACE_DATA, RACE)

    (events, entries, _lists), strings = gtdt_tables(race, [EVENT_SIZE, CAR_ENTRY_SIZE, 0x80])
    entries_off, = struct.unpack_from("<I", race, 8 + 8 * 1)

    setup, params, perf = SCRATCH, SCRATCH + 0x1000, SCRATCH + 0x2000
    cache = {}

    def car_stats(index):
        if index not in cache:
            game.write(setup, bytes(0x100))
            game.write(params, bytes(0x1c0))
            game.write(perf, bytes(0x6c))
            game.call(CARSETUP_INIT_FROM_CAR_ENTRY, RACE + entries_off + (index - 1) * CAR_ENTRY_SIZE, setup)
            game.call(CARPARAMS_BUILD_FROM_SETUP, setup, params)
            game.call(CARPARAMS_GET_PERFORMANCE, params, perf)
            power, = struct.unpack("<H", game.read(perf, 2))
            weight, = struct.unpack("<h", game.read(params + CARPARAMS_WEIGHT, 2))
            drive = game.read(params + CARPARAMS_DRIVETRAIN, 1)[0]
            car, = struct.unpack_from("<I", entries[index - 1])
            cache[index] = {"car": decode_car(car), "power": power, "weight": weight,
                            "drivetrain": DRIVETRAINS[drive]}
        return cache[index]

    out = []
    for e in events:
        code = strings[struct.unpack_from("<H", e, 0)[0]]
        ids = [i & 0xffff for i in struct.unpack_from("<16I", e, OPPONENT_IDS) if i]
        out.append({"code": code, "opponents": ids,
                    "powers": sorted(car_stats(i)["power"] for i in ids),
                    "weights": sorted(car_stats(i)["weight"] for i in ids)})

    entries_out = {str(i): cache[i] for i in sorted(cache)}
    json_out.write_text(json.dumps({"events": out, "entries": entries_out}, indent=1,
                                   ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    lines = [
        "# Event opponents",
        "",
        "Generated by `scripts/data/dump_opponents.py` from the Simulation disc (USA). "
        "`opponents.json` holds the same data, with the opponent entries of each event.",
        "",
        "- An event's opponents are drawn at random from its list of up to 16 car entries of the "
        "race data (`RaceSetup_InitEvent`). Each entry is a car with its own tuned setup, so the "
        "same car can have several entries.",
        "- **Power** and **weight** are what the game computes for an entry "
        "(`CarParams_GetPerformance`, as `BattleTable_LoadNext` does). The power is in the unit "
        "of the power limits.",
        "- The free races (`FREERACE*`, `FREECHAMP*`) don't use their list: `GTBattleMenu` draws "
        "the opponents from the car table, around the player's power. The rally events race one "
        "recorded car.",
        "",
        "| Code | Opponents | Min power | Median power | Max power | Median weight |",
        "|---|---|---|---|---|---|",
    ]
    for e in out:
        powers, weights = e["powers"], e["weights"]
        if not powers:
            lines.append("| %s | 0 | | | | |" % e["code"])
            continue
        lines.append("| %s | %d | %d | %d | %d | %d |" % (
            e["code"], len(powers), powers[0], statistics.median_low(powers), powers[-1],
            statistics.median_low(weights)))
    md_out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("events:", len(out), "car entries:", len(cache))


if __name__ == "__main__":
    main()
